load_apptainer() {
  module purge >/dev/null 2>&1 || true
  if ! command -v apptainer >/dev/null 2>&1; then
    module load apptainer >/dev/null 2>&1 || module load Apptainer >/dev/null 2>&1 || true
  fi
  command -v apptainer >/dev/null 2>&1 || { echo "[ERROR] apptainer not found" >&2; exit 1; }
}

# run <tool> <cmd...>  -> apptainer exec with /shares bound
run() {
  local tool=$1; shift
  local var="SIF_${tool^^}"
  [[ -s "${!var:-}" ]] || { echo "[ERROR] no container for $tool (did 00_setup finish?)" >&2; exit 1; }
  apptainer exec -B /shares:/shares "${!var}" "$@"
}

# manifest_get <sample_id> <column>
manifest_get() {
  awk -F'\t' -v s="$1" -v c="$2" 'NR==1{for(i=1;i<=NF;i++) h[$i]=i; next} $1==s{print $h[c]}' "$MANIFEST"
}
