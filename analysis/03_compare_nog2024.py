#!/usr/bin/env python3
"""Compare our DE results with the miRNAs reported by Nog et al., Transplant Proc 2024;56:1493
(n = 16, CLC Genomics, quantile normalisation, unadjusted p < 0.05 and |FC| >= 2).

Usage: python3 03_compare_nog2024.py <de_human_mirna.tsv> <de_viral_mirna.tsv> <out.tsv>
Writes the table plus a README.md next to it.
"""
import csv, os, sys

# As listed in the 2024 abstract (miRBase names completed with the hsa- prefix; arm as published)
NOG_UP = ["miR-16-5p", "miR-200c-3p", "bkv-miR-B1-3p", "let-7b-3p", "miR-1269b", "bkv-miR-B1-5p",
          "miR-193a-3p", "miR-944"]
NOG_DOWN = ["miR-134-5p", "miR-4724-5p", "miR-127-3p", "miR-6500-3p", "miR-507", "miR-378b", "miR-3911",
            "miR-211-5p", "miR-486-5p", "miR-143-3p", "miR-3195", "miR-1307-5p", "miR-29a-5p", "miR-378f",
            "miR-12136", "miR-378g", "miR-144-3p", "miR-378a-3p", "let-7i-5p", "miR-204-5p", "miR-146a-5p"]

de_h, de_v, out = sys.argv[1:4]
rows = {r["miRNA"]: r for f in (de_h, de_v) for r in csv.DictReader(open(f), delimiter="\t")}

def ours(name):
    key = name if name.startswith("bkv-") else "hsa-" + name
    return key, rows.get(key)

result = []
for direction, names in (("up", NOG_UP), ("down", NOG_DOWN)):
    for n in names:
        key, r = ours(n)
        if r is None:
            result.append([n, direction, "not tested (filtered: too few counts)", "", "", "", ""])
            continue
        lfc = float(r["log2FC"]) if r["log2FC"] not in ("", "NA") else None
        p = r.get("p_deseq2", "")
        q = r.get("q_deseq2", "")
        same = "" if lfc is None else ("yes" if (lfc > 0) == (direction == "up") else "no")
        result.append([n, direction, "tested", f"{lfc:.2f}" if lfc is not None else "NA", p, q, same])

hdr = ["miRNA", "nog2024_direction", "status_here", "log2FC_here", "p_here", "q_here", "same_direction"]
with open(out, "w", newline="") as fh:
    w = csv.writer(fh, delimiter="\t"); w.writerow(hdr); w.writerows(result)

tested = [r for r in result if r[2] == "tested"]
same = sum(r[6] == "yes" for r in tested)
nom = [r for r in tested if r[4] not in ("", "NA") and float(r[4]) < 0.05]
print(f"Nog 2024 reported {len(result)} miRNAs; {len(tested)} passed our expression filter; "
      f"same direction: {same}/{len(tested)}; nominal p<0.05 here: {len(nom)} "
      f"({', '.join(r[0] for r in nom)})")

with open(os.path.join(os.path.dirname(out) or ".", "README.md"), "w") as fh:
    fh.write("# Comparison with Nog et al. 2024 (generated by analysis/03_compare_nog2024.py; do not edit by hand)\n\n"
             "Nog et al., *Transplant Proc* 2024;56:1493 reported 8 up- and 21 down-regulated urinary miRNAs "
             "(n = 16; unadjusted p < 0.05, |FC| >= 2). This table looks each of them up in our DESeq2 results.\n\n"
             "| Column | Meaning |\n|---|---|\n"
             "| `nog2024_direction` | Direction reported in 2024 (DNAemia vs control). |\n"
             "| `status_here` | `tested` or removed by our expression filter (`filterByExpr`). |\n"
             "| `log2FC_here`, `p_here`, `q_here` | Our DESeq2 log2FC, p and BH q (q is NA if DESeq2 flagged an outlier). |\n"
             "| `same_direction` | Whether our fold change points the same way. |\n")
