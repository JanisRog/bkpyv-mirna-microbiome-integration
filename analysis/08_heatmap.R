#!/usr/bin/env Rscript
# Figure 2A: Spearman correlations, nominally DE miRNAs (+ viral) vs bacterial genera, paired samples.
# Specified before running (PROJECT_LOG 2026-10-16):
#   miRNAs  : human miRNAs with DESeq2 p < 0.05 (Fig 1A) + bkv-miR-B1-5p, bkv-miR-B1-3p; DESeq2-normalised counts
#   genera  : present (> 0) in >= 3 of the paired samples, after the mean-RA > 0.1% filter; CLR of relative
#             abundance (pseudocount = half the smallest non-zero value)
#   extra   : urinary BKPyV DNA (pairs per million QC pairs) as a positive-control column
#   stats   : Spearman rho (exact p); BH-FDR over all miRNA x column pairs
#
# Usage: Rscript 08_heatmap.R <genus_relative_abundance.tsv> <de_dir> <qc_combined.tsv> <out_dir>
suppressPackageStartupMessages({ library(readr); library(dplyr); library(tidyr); library(ggplot2) })
args <- commandArgs(trailingOnly = TRUE)
if (length(args) != 4) stop("usage: 08_heatmap.R <genus_relative_abundance.tsv> <de_dir> <qc_combined.tsv> <out_dir>")
out <- args[4]; dir.create(out, showWarnings = FALSE, recursive = TRUE)
MIN_PREV <- 3; VIRAL <- c("bkv-miR-B1-5p", "bkv-miR-B1-3p")

samples <- read_tsv(file.path(args[2], "samples_used.tsv"), show_col_types = FALSE)$sample_id
de   <- read_tsv(file.path(args[2], "de_human_mirna.tsv"), show_col_types = FALSE)
norm <- read_tsv(file.path(args[2], "normalized_counts_deseq2.tsv"), show_col_types = FALSE)
qc   <- read_tsv(args[3], show_col_types = FALSE) |> filter(sample_id %in% samples)
gra  <- read_tsv(args[1], show_col_types = FALSE)
stopifnot(all(samples %in% names(gra)))

up   <- de |> filter(nominal, log2FC > 0) |> arrange(p_deseq2) |> pull(miRNA)
down <- de |> filter(nominal, log2FC < 0) |> arrange(p_deseq2) |> pull(miRNA)
mir  <- c(up, down, VIRAL)
mx <- as.matrix(norm[match(mir, norm$miRNA), samples]); rownames(mx) <- mir

g <- as.matrix(gra[, samples]); rownames(g) <- gra$genus
g <- g[rowSums(g > 0) >= MIN_PREV, , drop = FALSE]
pc <- min(g[g > 0]) / 2
clr <- log(g + pc); clr <- sweep(clr, 2, colMeans(log(as.matrix(gra[, samples]) + pc)), "-")
cols <- rbind(clr, `Urinary BKPyV DNA` = qc$mg_bk_per_million_qc[match(samples, qc$sample_id)])

res <- expand_grid(miRNA = mir, feature = rownames(cols)) |> rowwise() |>
  mutate(ct = list(suppressWarnings(cor.test(mx[miRNA, ], cols[feature, ], method = "spearman", exact = TRUE))),
         rho = unname(ct$estimate), p = ct$p.value) |> ungroup() |> select(-ct) |>
  mutate(q = p.adjust(p, "BH"), mark = case_when(q < 0.05 ~ "q<0.05", p < 0.05 ~ "p<0.05", TRUE ~ ""))

# genera ordered by clustering of their correlation profiles; BK DNA column last
gm <- res |> filter(feature != "Urinary BKPyV DNA") |> select(miRNA, feature, rho) |>
  pivot_wider(names_from = feature, values_from = rho) |> select(-miRNA) |> as.matrix()
g_ord <- colnames(gm)[hclust(dist(t(replace(gm, is.na(gm), 0))))$order]
pd <- res |> mutate(feature = factor(feature, levels = c(g_ord, "Urinary BKPyV DNA")),
                    miRNA = factor(miRNA, levels = rev(mir)),
                    lab = ifelse(miRNA == "bkv-miR-B1-3p", "bkv-miR-B1-3p / jcv-miR-J1-3p", sub("^hsa-", "", miRNA)))
ylab <- setNames(pd$lab, pd$miRNA)[levels(pd$miRNA)]
hm <- ggplot(pd, aes(feature, miRNA, fill = rho)) +
  geom_tile(colour = "white", linewidth = 0.4) +
  geom_point(data = ~ dplyr::filter(.x, mark == "p<0.05"), size = 1.3) +
  geom_text(data = ~ dplyr::filter(.x, mark == "q<0.05"), label = "*", size = 4.5, vjust = 0.75) +
  geom_vline(xintercept = length(g_ord) + 0.5, linewidth = 0.6) +
  geom_hline(yintercept = c(length(VIRAL) + 0.5, length(VIRAL) + length(down) + 0.5), linewidth = 0.4, colour = "grey30") +
  scale_fill_gradient2(low = "#2166AC", mid = "white", high = "#B2182B", limits = c(-1, 1), name = "Spearman\nrho") +
  scale_y_discrete(labels = ylab) +
  # the FDR symbol is only explained if any pair reaches q < 0.05 (none did; stated in the text instead)
  labs(x = NULL, y = NULL, caption = sprintf("n = %d paired samples. Dot: nominal p < 0.05%s.", length(samples),
                                             if (any(res$q < 0.05)) "; *: FDR q < 0.05" else "")) +
  theme_minimal(base_size = 10) +
  scale_x_discrete(labels = function(x) parse(text = ifelse(x == "Urinary BKPyV DNA", "bold('Urinary BKPyV DNA')",
                                                             sprintf("italic('%s')", x)))) +
  theme(axis.text.x = element_text(angle = 50, hjust = 1),
        panel.grid = element_blank(), plot.caption = element_text(size = 8))
saveRDS(hm, file.path(out, "Fig2A_heatmap.rds"))
ggsave(file.path(out, "Fig2A_heatmap.pdf"), hm, width = 7.5, height = 6.2, bg = "white")
ggsave(file.path(out, "Fig2A_heatmap.png"), hm, width = 7.5, height = 6.2, dpi = 300, bg = "white")

write_tsv(res |> arrange(p), file.path(out, "correlations.tsv"))
writeLines(c(
  "# Figure 2A: miRNA x genus correlations (generated by analysis/08_heatmap.R; do not edit by hand)", "",
  sprintf("Samples: the %d paired samples. Specified before running (PROJECT_LOG 2026-10-16).", length(samples)), "",
  "| File | Contents |", "|---|---|",
  "| `correlations.tsv` | Every miRNA x feature pair: Spearman `rho`, exact `p`, BH `q` over all pairs, `mark` (q<0.05 / p<0.05; drawn as * / dot). |",
  "| `Fig2A_heatmap.pdf/.png` | Heatmap; rows: nominally up / down human miRNAs, then viral; columns: genera (clustered) and urinary BKPyV DNA. |",
  "| `Fig2A_heatmap.rds` | ggplot object for `analysis/07_main_figures.R`. |", "",
  sprintf("miRNAs: human miRNAs with nominal DESeq2 p < 0.05 in Fig 1A (%d up, %d down) plus bkv-miR-B1-5p and bkv-miR-B1-3p (= jcv-miR-J1-3p); DESeq2-normalised counts.", length(up), length(down)),
  sprintf("Genera: present in >= %d of %d samples after the mean relative abundance > 0.1%% filter (%d genera); centred log-ratio of relative abundance, pseudocount = half the smallest non-zero value.", MIN_PREV, length(samples), nrow(g)),
  "Urinary BKPyV DNA: BK read pairs per million QC read pairs (metagenome); positive control for the viral miRNAs.",
  "With n = 11, |rho| >= 0.62 is needed for nominal p < 0.05."
), file.path(out, "README.md"))
writeLines(capture.output(sessionInfo()), file.path(out, "sessionInfo.txt"))
cat(sprintf("miRNAs %d (up %d, down %d, viral 2) | genera %d | pairs %d | nominal p<0.05: %d | q<0.05: %d\n",
            length(mir), length(up), length(down), nrow(g), nrow(res), sum(res$p < 0.05), sum(res$q < 0.05)))
print(as.data.frame(res |> arrange(p) |> head(12) |> mutate(rho = round(rho, 2), p = signif(p, 2), q = signif(q, 2))))
