#!/usr/bin/env Rscript
# Supplementary figures from saved panel objects.
#   S1  volcano of the sensitivity set (>=10k human miRNA reads)            <- 02_mirna_de.R sensitivity run
#   S2  microbiome sensitivity: all samples / spillover removed / without the bacteriuric control
#       (rarefied richness + Shannon, and Aitchison PCA per row)          <- 05_microbiome.R runs
#   S3  miR-200 family check                                              <- 04_mir200_shedding.R (copied)
#
# Usage: Rscript 09_supp_figures.R <de_sensitivity_dir> <mb_primary> <mb_crosstalk> <mb_without_S18> <mir200_dir> <out_dir>
suppressPackageStartupMessages({ library(ggplot2); library(patchwork); library(dplyr); library(ggrepel) })
a <- commandArgs(trailingOnly = TRUE)
if (length(a) != 6) stop("usage: 09_supp_figures.R <de_sens> <mb_primary> <mb_crosstalk> <mb_noS18> <mir200_dir> <out_dir>")
out <- a[6]; dir.create(out, showWarnings = FALSE, recursive = TRUE)

s1 <- readRDS(file.path(a[1], "Fig1A_volcano.rds")) + theme(legend.position = "top")
ggsave(file.path(out, "FigureS1.pdf"), s1, width = 8, height = 6.5, bg = "white")
ggsave(file.path(out, "FigureS1.png"), s1, width = 8, height = 6.5, dpi = 300, bg = "white")

rows <- list(c(a[2], "All samples (as Figure 1C, D)"),
             c(a[3], "Probable cross-sample spillover removed"),
             c(a[4], "Without the bacteriuric control (S18)"))
row_plot <- function(dir, title) {
  p <- readRDS(file.path(dir, "fig_panels.rds"))
  (wrap_elements(full = p$alpha) | wrap_elements(full = p$pca + theme(legend.position = "none"))) +
    plot_layout(widths = c(1, 1.1)) + plot_annotation(title = title)
}
heading <- function(txt) ggplot() + annotate("text", x = 0, y = 0.5, label = txt, hjust = 0, size = 4.6, fontface = "bold") +
  xlim(0, 1) + ylim(0, 1) + theme_void()
parts <- list()
for (r in rows) {
  p <- readRDS(file.path(r[1], "fig_panels.rds"))
  parts <- c(parts, list(heading(r[2]),
    wrap_elements(full = (p$alpha | (p$pca + theme(legend.position = "none"))) + plot_layout(widths = c(1, 1.1)))))
}
s2 <- wrap_plots(parts, ncol = 1, heights = rep(c(0.07, 1), 3)) +
  plot_annotation(caption = "Blue, controls; red, BKPyV DNAemia. p values: exact Wilcoxon (box plots) and PERMANOVA (PCA).")
ggsave(file.path(out, "FigureS2.pdf"), s2, width = 11, height = 14, bg = "white")
ggsave(file.path(out, "FigureS2.png"), s2, width = 11, height = 14, dpi = 300, bg = "white")

for (ext in c("pdf", "png")) file.copy(file.path(a[5], paste0("FigS_mir200_shedding.", ext)),
                                        file.path(out, paste0("FigureS3.", ext)), overwrite = TRUE)
writeLines(c(
  "# Supplementary figures (generated by analysis/09_supp_figures.R; do not edit by hand)", "",
  "| File | Contents |", "|---|---|",
  "| `FigureS1.*` | Differential expression in the sensitivity set (>=10,000 human miRNA reads; 8 DNAemia vs 6 controls). |",
  "| `FigureS2.*` | Microbiome alpha diversity (rarefied richness, Shannon) and Aitchison PCA: all samples; probable spillover removed (counts < 1% of the taxon's maximum; S14 has no bacteria left and is dropped); without control S18 (E. coli bacteriuria). |",
  "| `FigureS3.*` | miR-200 family score vs human DNA fraction and urinary BKPyV DNA; cell-origin miRNA profile (copy of results/integration/mir200_shedding). |"
), file.path(out, "README.md"))
writeLines(capture.output(sessionInfo()), file.path(out, "sessionInfo.txt"))
