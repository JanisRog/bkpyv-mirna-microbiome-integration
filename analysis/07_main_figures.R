#!/usr/bin/env Rscript
# Assemble the main figures from saved panel objects.
#   Figure 1 (independent analyses, each with all samples passing its own QC)
#     A  volcano (02_mirna_de.R, miRNA analysis set)
#     B  alpha diversity, C  Aitchison PCA (05_microbiome.R, all samples passing metagenome QC)
#   Figure 2 (integration, paired samples)
#     A  miRNA x genus correlation heatmap (08_heatmap.R)
#     B  descriptive Sankey (06_sankey.R)
#
# Usage: Rscript 07_main_figures.R <de_primary_dir> <microbiome_all_dir> <heatmap_dir> <sankey_dir> <out_dir>
suppressPackageStartupMessages({ library(ggplot2); library(patchwork); library(dplyr); library(ggrepel) })  # dplyr/ggrepel needed to redraw saved panels
args <- commandArgs(trailingOnly = TRUE)
if (length(args) != 5) stop("usage: 07_main_figures.R <de_primary_dir> <microbiome_all_dir> <heatmap_dir> <sankey_dir> <out_dir>")
out <- args[5]; dir.create(out, showWarnings = FALSE, recursive = TRUE)

vol <- readRDS(file.path(args[1], "Fig1A_volcano.rds"))
mb  <- readRDS(file.path(args[2], "fig_panels.rds"))
f1 <- (vol + theme(legend.position = "top")) |
      (mb$alpha / (mb$pca + theme(legend.position = "none")) + plot_layout(heights = c(1, 1.1)))
f1 <- f1 + plot_layout(widths = c(1.35, 1)) + plot_annotation(tag_levels = "A")
ggsave(file.path(out, "Figure1.pdf"), f1, width = 12, height = 6.8, bg = "white")
ggsave(file.path(out, "Figure1.png"), f1, width = 12, height = 6.8, dpi = 300, bg = "white")

hm <- readRDS(file.path(args[3], "Fig2A_heatmap.rds"))
sk <- readRDS(file.path(args[4], "Fig2_sankey.rds"))
# wrap_elements: each panel keeps its own layout (the Sankey must not be aligned to the heatmap's axes)
f2 <- wrap_plots(wrap_elements(full = hm), wrap_elements(full = sk), ncol = 1, heights = c(0.78, 1)) +
  plot_annotation(tag_levels = "A")
ggsave(file.path(out, "Figure2.pdf"), f2, width = 12, height = 15.5, bg = "white")
ggsave(file.path(out, "Figure2.png"), f2, width = 12, height = 15.5, dpi = 300, bg = "white")

writeLines(c(
  "# Main figures (Figure 1 generated by analysis/07_main_figures.R; do not edit by hand)", "",
  "| File | Contents |", "|---|---|",
  "| `Figure1.pdf/.png` | Independent analyses. A: volcano, DNAemia vs control (miRNA analysis set, ERCC criterion 1). B: alpha diversity and C: Aitchison PCA (all samples passing metagenome QC). |",
  "| `Figure2.pdf/.png` | Integration in the paired samples. A: Spearman correlations, nominally DE miRNAs + viral vs genera and urinary BKPyV DNA. B: descriptive Sankey genus -> sample -> miRNA. |", "",
  "Colours: control blue, DNAemia red."
), file.path(out, "README.md"))
writeLines(capture.output(sessionInfo()), file.path(out, "sessionInfo.txt"))
