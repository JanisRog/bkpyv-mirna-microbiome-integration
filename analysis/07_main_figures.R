#!/usr/bin/env Rscript
# Assemble main Figure 1 from saved panel objects (same paired samples throughout):
#   A  volcano (02_mirna_de.R, primary set)
#   B  alpha diversity + Aitchison PCA of the same samples (05_microbiome.R, paired run)
# Figure 2 (Sankey) is written directly by 06_sankey.R.
#
# Usage: Rscript 07_main_figures.R <de_primary_dir> <microbiome_paired_dir> <out_dir>
suppressPackageStartupMessages({ library(ggplot2); library(patchwork); library(dplyr); library(ggrepel) })  # dplyr/ggrepel needed to redraw saved panels
args <- commandArgs(trailingOnly = TRUE)
if (length(args) != 3) stop("usage: 07_main_figures.R <de_primary_dir> <microbiome_paired_dir> <out_dir>")
out <- args[3]; dir.create(out, showWarnings = FALSE, recursive = TRUE)

vol <- readRDS(file.path(args[1], "Fig1A_volcano.rds"))
mb  <- readRDS(file.path(args[2], "fig_panels.rds"))
f1 <- (vol + theme(legend.position = "top")) |
      (mb$alpha / (mb$pca + theme(legend.position = "none")) + plot_layout(heights = c(1, 1.1)))
f1 <- f1 + plot_layout(widths = c(1.35, 1)) + plot_annotation(tag_levels = "A")
ggsave(file.path(out, "Figure1.pdf"), f1, width = 12, height = 6.8, bg = "white")
ggsave(file.path(out, "Figure1.png"), f1, width = 12, height = 6.8, dpi = 300, bg = "white")

writeLines(c(
  "# Main figures (Figure 1 generated by analysis/07_main_figures.R; do not edit by hand)", "",
  "| File | Contents |", "|---|---|",
  "| `Figure1.pdf/.png` | A: volcano, DNAemia vs control (miRNA analysis set). B: alpha diversity (top) and Aitchison PCA (bottom) of the same samples. |",
  "| `Figure2_sankey.pdf/.png` | Copy of `integration/sankey/Fig2_sankey.*` (descriptive Sankey, same samples). |", "",
  "All panels use the same paired samples (ERCC criterion 1 pass; all have metagenomes). Colours: control blue, DNAemia red."
), file.path(out, "README.md"))
writeLines(capture.output(sessionInfo()), file.path(out, "sessionInfo.txt"))
