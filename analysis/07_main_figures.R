#!/usr/bin/env Rscript
# Assemble the main figures from saved panel objects.
#   Figure 1 (independent analyses), 2 x 2
#     A  small-RNA yield, all samples, ERCC criterion-1 line (01_mirna_yield.R)
#     B  volcano (02_mirna_de.R, miRNA analysis set = ERCC criterion 1)
#     C  alpha diversity, D  Aitchison PCA (05_microbiome.R, all samples passing metagenome QC)
#   Figure 2 (integration, paired samples)
#     A  miRNA x genus correlation heatmap (08_heatmap.R)
#     B  descriptive Sankey (06_sankey.R)
#
# Usage: Rscript 07_main_figures.R <yield_dir> <de_primary_dir> <microbiome_all_dir> <heatmap_dir> <sankey_dir> <out_dir>
suppressPackageStartupMessages({ library(ggplot2); library(patchwork); library(dplyr); library(ggrepel) })  # dplyr/ggrepel needed to redraw saved panels
args <- commandArgs(trailingOnly = TRUE)
if (length(args) != 6) stop("usage: 07_main_figures.R <yield_dir> <de_primary_dir> <microbiome_all_dir> <heatmap_dir> <sankey_dir> <out_dir>")
out <- args[6]; dir.create(out, showWarnings = FALSE, recursive = TRUE)

yl  <- readRDS(file.path(args[1], "Fig1A_yield.rds"))
vol <- readRDS(file.path(args[2], "Fig1A_volcano.rds"))
mb  <- readRDS(file.path(args[3], "fig_panels.rds"))
# top row: narrow yield panel, wide volcano with its legend on top in a single row; bottom row: alpha | PCA
vol_r <- vol + theme(legend.position = "top", legend.margin = margin(0, 0, 0, 0)) +
  guides(colour = guide_legend(nrow = 1), shape = guide_legend(nrow = 1))
top <- wrap_elements(full = yl) | wrap_elements(full = vol_r)
bot <- wrap_elements(full = mb$alpha) | wrap_elements(full = mb$pca + theme(legend.position = "bottom"))
f1 <- (top + plot_layout(widths = c(0.62, 1.38))) / (bot + plot_layout(widths = c(1, 1.15))) +
  plot_annotation(tag_levels = "A")
ggsave(file.path(out, "Figure1.pdf"), f1, width = 12, height = 10, bg = "white")
ggsave(file.path(out, "Figure1.png"), f1, width = 12, height = 10, dpi = 300, bg = "white")

hm <- readRDS(file.path(args[4], "Fig2A_heatmap.rds"))
sk <- readRDS(file.path(args[5], "Fig2_sankey.rds"))
# wrap_elements: each panel keeps its own layout (the Sankey must not be aligned to the heatmap's axes)
f2 <- wrap_plots(wrap_elements(full = hm), wrap_elements(full = sk), ncol = 1, heights = c(0.78, 1)) +
  plot_annotation(tag_levels = "A")
ggsave(file.path(out, "Figure2.pdf"), f2, width = 12, height = 15.5, bg = "white")
ggsave(file.path(out, "Figure2.png"), f2, width = 12, height = 15.5, dpi = 300, bg = "white")

writeLines(c(
  "# Main figures (generated by analysis/07_main_figures.R; do not edit by hand)", "",
  "| File | Contents |", "|---|---|",
  "| `Figure1.pdf/.png` | Independent analyses. A: small-RNA yield in all samples (human miRNA reads; reads on annotated RNA with the ERCC criterion-1 line). B: volcano, DNAemia vs control (miRNA analysis set, ERCC criterion 1). C: alpha diversity and D: Aitchison PCA (all samples passing metagenome QC). |",
  "| `Figure2.pdf/.png` | Integration in the paired samples. A: Spearman correlations, nominally DE miRNAs + viral vs genera and urinary BKPyV DNA. B: descriptive Sankey genus -> sample -> miRNA. |", "",
  "Colours: control blue, DNAemia red.", "",
  "`FIGURE_LEGENDS_draft.md` (hand-written, not generated): draft legends for Figures 1 and 2 with all definitions; numbers must be updated if analyses are rerun."
), file.path(out, "README.md"))
writeLines(capture.output(sessionInfo()), file.path(out, "sessionInfo.txt"))
